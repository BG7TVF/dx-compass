/**
 * Build the shared 50m country-border outline used by every map view.
 *
 * Input:  Natural Earth 50m admin-0 boundary lines (GeoJSON, pinned release).
 * Output: public/shared/map/data/borders-50m.js -> window.MAP_BORDERS
 *
 * The pipeline matches the coastline data in the same folder: 3-decimal
 * coordinates and Douglas-Peucker 0.05 deg, so borders and coastlines keep the
 * same precision and the same rendering path. Lines are cut at the
 * antimeridian so Leaflet never draws a stripe across the whole world.
 *
 * Usage: node scripts/build-map-data.mjs [local.geojson]
 */
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {gzipSync} from 'node:zlib';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = path.join(ROOT, 'public', 'shared', 'map', 'data', 'borders-50m.js');
const SOURCE = 'ne_50m_admin_0_boundary_lines_land.geojson';
/* Pinned release instead of master: the generated byte size and point count
 * stay reproducible even if Natural Earth publishes a newer dataset. */
const RELEASE = 'v5.1.2';
const URL = `https://raw.githubusercontent.com/nvkelso/natural-earth-vector/${RELEASE}/geojson/${SOURCE}`;
const TOLERANCE = 0.05;
const DECIMALS = 3;

function round(value) {
    const factor = 10 ** DECIMALS;
    return Math.round(value * factor) / factor;
}

/** Squared distance from p to segment ab, all in lon/lat degrees. */
function segmentDistanceSquared(p, a, b) {
    let x = a[0];
    let y = a[1];
    let dx = b[0] - x;
    let dy = b[1] - y;
    if (dx || dy) {
        const t = ((p[0] - x) * dx + (p[1] - y) * dy) / (dx * dx + dy * dy);
        if (t > 1) {
            x = b[0];
            y = b[1];
        } else if (t > 0) {
            x += dx * t;
            y += dy * t;
        }
    }
    dx = p[0] - x;
    dy = p[1] - y;
    return dx * dx + dy * dy;
}

/** Iterative Douglas-Peucker (no recursion limit on long coastlines). */
function simplify(points, tolerance = TOLERANCE) {
    if (points.length <= 2) return points;
    const threshold = tolerance * tolerance;
    const keep = new Uint8Array(points.length);
    keep[0] = 1;
    keep[points.length - 1] = 1;
    const stack = [[0, points.length - 1]];
    while (stack.length) {
        const [first, last] = stack.pop();
        let index = 0;
        let farthest = threshold;
        for (let i = first + 1; i < last; i++) {
            const distance = segmentDistanceSquared(points[i], points[first], points[last]);
            if (distance > farthest) {
                farthest = distance;
                index = i;
            }
        }
        if (!index) continue;
        keep[index] = 1;
        stack.push([first, index], [index, last]);
    }
    return points.filter((point, index) => keep[index]);
}

/** Round, drop duplicates, then split wherever a line jumps the antimeridian. */
function normalizeLine(points) {
    const rounded = [];
    for (const point of points) {
        const lon = round(Number(point[0]));
        const lat = round(Number(point[1]));
        if (!Number.isFinite(lon) || !Number.isFinite(lat)) continue;
        const previous = rounded[rounded.length - 1];
        if (previous && previous[0] === lon && previous[1] === lat) continue;
        rounded.push([lon, lat]);
    }
    if (rounded.length < 2) return [];
    const lines = [];
    let current = [rounded[0]];
    for (let i = 1; i < rounded.length; i++) {
        const previous = rounded[i - 1];
        const point = rounded[i];
        if (Math.abs(point[0] - previous[0]) > 180) {
            if (current.length > 1) lines.push(current);
            current = [point];
            continue;
        }
        current.push(point);
    }
    if (current.length > 1) lines.push(current);
    return lines;
}

function collectLines(geojson) {
    const lines = [];
    for (const feature of (geojson && geojson.features) || []) {
        const geometry = feature && feature.geometry;
        if (!geometry) continue;
        if (geometry.type === 'LineString') lines.push(geometry.coordinates);
        else if (geometry.type === 'MultiLineString') lines.push(...geometry.coordinates);
    }
    return lines;
}

async function loadSource() {
    const local = process.argv[2];
    if (local) return JSON.parse(await readFile(path.resolve(local), 'utf8'));
    const response = await fetch(URL);
    if (!response.ok) throw new Error(`download failed: ${response.status} ${URL}`);
    return response.json();
}

const source = await loadSource();
const rawLines = collectLines(source);
const output = [];
for (const raw of rawLines) {
    const simplified = simplify(raw.map(point => [Number(point[0]), Number(point[1])]));
    for (const line of normalizeLine(simplified)) {
        output.push([].concat(...line));
    }
}

const points = output.reduce((sum, line) => sum + line.length / 2, 0);
const header = '/* Country borders (Natural Earth 50m admin-0 boundary lines).\n' +
    ` * Source: ${SOURCE} @ ${RELEASE}. Public domain (Natural Earth).\n` +
    ` * Douglas-Peucker ${TOLERANCE} deg, ${DECIMALS}-decimal lon/lat, antimeridian cut.\n` +
    ` * Generated by scripts/build-map-data.mjs; do not edit by hand.\n` +
    ` * ${output.length} lines / ${points} points. */\n`;
const body = 'window.MAP_BORDERS=[' + output.map(line => '[' + line.join(',') + ']').join(',\n') + '];\n';
const text = header + body;

await mkdir(path.dirname(OUTPUT), {recursive: true});
await writeFile(OUTPUT, text, 'utf8');

const bytes = Buffer.byteLength(text);
const gzip = gzipSync(text).length;
console.log(`${path.relative(ROOT, OUTPUT)}: ${output.length} lines / ${points} points / ` +
    `${bytes} B (${gzip} B gzip)`);
