/* Merge the namespaced settings/wall vocabulary. Keys never collide with
 * the legacy flat dictionary; locales without an entry inherit English. */
const I18N_MERGE_DUPLICATES = [];
for (const l of LANGS) {
    const extra = I18N_EXTRA[l] || {};
    for (const key of Object.keys(I18N_EXTRA.en)) {
        if (Object.prototype.hasOwnProperty.call(I18N[l], key)) {
            I18N_MERGE_DUPLICATES.push(l + ':' + key);
            continue;
        }
        I18N[l][key] = Object.prototype.hasOwnProperty.call(extra, key) ? extra[key] : I18N_EXTRA.en[key];
    }
}
if (typeof globalThis !== 'undefined') globalThis.I18N_MERGE_DUPLICATES = I18N_MERGE_DUPLICATES;
